-- Unique shareable ID in the form "user<6-digit-number>" (e.g.
-- "user163745") -- a random number, not sequential, so ids can't be
-- enumerated/guessed, generated by generate_unique_public_id() below,
-- which loops until it finds one not already in use. security definer so
-- that uniqueness check sees every row in the table regardless of who's
-- triggering it -- an ordinary authenticated user's own SELECT on
-- `profiles` only sees their own/connections' rows per RLS, which would
-- make the "not exists" check unreliable without this.
create or replace function public.generate_unique_public_id()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  candidate text;
begin
  loop
    candidate := 'user' || (100000 + floor(random() * 900000))::bigint::text;
    exit when not exists (select 1 from public.profiles where public_id = candidate);
  end loop;
  return candidate;
end;
$$;

grant execute on function public.generate_unique_public_id() to authenticated;

