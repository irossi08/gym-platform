-- A member can see every membership row for any community they themselves
-- belong to (so the full member list renders for them), not just their
-- own row. The naive way to write this is a subquery on community_members
-- from within community_members' own policy -- that looks like the
-- standard "group membership" RLS pattern seen in a lot of writeups, but
-- it actually makes Postgres throw "infinite recursion detected in policy
-- for relation community_members" (42P17), because evaluating the policy
-- requires re-evaluating the same policy on the same table. Worse, that
-- error doesn't stay contained: profiles_select_connections (further
-- down) also queries community_members to check shared-community
-- membership, so ANY query touching profiles' SELECT visibility --
-- including an upsert's ON CONFLICT check -- transitively re-triggers this
-- same recursion and fails with an error that looks like it's about a
-- completely unrelated table. is_community_member() sidesteps this: it's
-- security definer, so its internal query bypasses RLS entirely instead
-- of re-invoking community_members_select.
create or replace function public.is_community_member(p_community_id uuid, p_user_id uuid)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.community_members
    where community_id = p_community_id and user_id = p_user_id
  );
$$;

grant execute on function public.is_community_member(uuid, uuid) to authenticated;

drop policy if exists "community_members_select" on public.community_members;
create policy "community_members_select" on public.community_members
  for select using (
    user_id = auth.uid()
    or public.is_community_member(community_id, auth.uid())
  );

-- Joining a PUBLIC community directly needs no invite code -- straight
-- insert. Joining a PRIVATE one is NOT permitted through this policy (no
-- code check is expressible in a column-only RLS predicate); that path
-- goes through join_community_by_code() below instead, which runs as
-- security definer specifically so a private community can be joined
-- without ever being SELECT-able by non-members first. The creator is
-- always allowed to add themselves regardless of visibility, so creating a
-- private community still auto-joins its own creator via a plain insert.
--
-- "Invite a friend to a community you created" (App.Communities.
-- inviteFriendToCommunity) does NOT insert here directly -- it goes
-- through community_invites below instead, requiring the friend to
-- accept. accept_community_invite() is security definer, so it performs
-- that eventual membership insert bypassing RLS entirely; this policy
-- deliberately does NOT grant the invited user (or the creator on their
-- behalf) any direct insert path, so the only way into a community you
-- didn't create/self-join-as-public is accepting an invite or a code.
drop policy if exists "community_members_insert" on public.community_members;
create policy "community_members_insert" on public.community_members
  for insert with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.communities c
      where c.id = community_id and (c.visibility = 'public' or c.created_by = auth.uid())
    )
  );

drop policy if exists "community_members_delete" on public.community_members;
create policy "community_members_delete" on public.community_members
  for delete using (user_id = auth.uid());

